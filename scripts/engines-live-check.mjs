async function http(url, opts = {}, timeoutMs = 60000) {
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), timeoutMs);
  try {
    const r = await fetch(url, { ...opts, signal: ctl.signal });
    const ct = r.headers.get("content-type") || "";
    const body = ct.startsWith("image/") ? Buffer.from(await r.arrayBuffer()) : await r.text();
    return { status: r.status, ok: r.ok, ct, body };
  } finally {
    clearTimeout(t);
  }
}
const jsonOf = (b) => { try { return JSON.parse(b); } catch { return null; } };
