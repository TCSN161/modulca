/* ── Cloudflare helpers ─────────────────────────────────────────────── */
const CF = `https://api.cloudflare.com/client/v4/accounts/${E.CLOUDFLARE_ACCOUNT_ID}/ai/run/`;
async function cfJson(model, body) {
  const r = await http(CF + model, { method: "POST", headers: bearer(E.CLOUDFLARE_API_TOKEN), body: JSON.stringify(body) });
  const j = jsonOf(r.body);
  const b64 = j?.result?.image;
  return r.ok && b64 ? img(Buffer.from(b64, "base64")) : fail(r);
}
async function cfMultipart(model, fields, withImage) {
  const fd = new FormData();
  for (const [k, v] of Object.entries(fields)) fd.append(k, String(v));
  if (withImage) {
    if (!baseImage) return { result: "SKIP", err: "no base image (cf-flux1 failed and BASE_IMAGE unset)" };
    fd.append("input_image_0", new Blob([baseImage], { type: "image/jpeg" }), "base.jpg");
  }
  // Workers AI REST: multipart models take the form as the raw body.
  const r = await http(CF + model, { method: "POST", headers: { Authorization: `Bearer ${E.CLOUDFLARE_API_TOKEN}` }, body: fd }, 90000);
  const j = jsonOf(r.body);
  const b64 = j?.result?.image;
  return r.ok && b64 ? img(Buffer.from(b64, "base64"), withImage ? "img2img (input_image_0)" : "") : fail(r);
}

